"""Web3 integration layer for interacting with on-chain smart contracts.

Provides a :class:`BlockchainClient` that wraps calls to the four Solidity
contracts specified in the design document:

- **IdentityRegistry** – DID ↔ wallet mapping
- **BiometricCommitmentRegistry** – template commitment storage
- **AccessPolicyRegistry** – on-chain policy hashes
- **AuditLog** – immutable access-event log

All operations degrade gracefully when the blockchain provider is unavailable
or the ``web3`` package is not installed.
"""

from __future__ import annotations

import importlib.util
import json
import logging
import os
from dataclasses import dataclass
from typing import Any, Dict, List, Optional

logger = logging.getLogger(__name__)

_WEB3_AVAILABLE = importlib.util.find_spec("web3") is not None

